class Command(BaseCommand):
    help = 'Seed curated, verified computer hardware catalog and compatibility matrix (idempotent).'

    @transaction.atomic
    def handle(self, *args, **options):
        cat_init_result = initialize_starter_categories(overwrite_existing=False)
        cat_map = cat_init_result['categories_by_slug']

        brand_map = {}
        for bname in BRANDS:
            b, _ = Brand.objects.get_or_create(
                slug=slugify(bname),
                defaults={'name': bname},
            )
            brand_map[bname] = b

        # Chipset-CPU compatibility rules
        for socket, chipset, family, status, notes, src in CHIPSET_CPU_MATRIX:
            ChipsetCPUSupport.objects.update_or_create(
                socket=socket,
                chipset=chipset,
                cpu_family=family,
                defaults={
                    'status': status,
                    'notes': notes,
                    'source_reference': src,
                },
            )

        # Enrich existing legacy CPUs from original db.sqlite3 without deleting them
        seen_legacy_names = set()
        for prod in Product.objects.filter(legacy_category='Processors').order_by('id'):
            if prod.name in seen_legacy_names:
                # Deactivate exact duplicate legacy entry #4 while preserving row
                prod.is_active = False
                prod.save(update_fields=['is_active'])
                continue
            seen_legacy_names.add(prod.name)

            meta = LEGACY_CPU_SPECS.get(prod.name)
            if meta:
                prod.category = cat_map['processors']
                prod.brand = brand_map['AMD']
                prod.short_description = meta['short_description']
                prod.spec_source = meta['spec_source']
                prod.spec_verified = True
                prod.is_active = True
                prod.save()
                Inventory.objects.get_or_create(product=prod, defaults={'quantity': 10})
                HardwareSpecProfile.objects.update_or_create(product=prod, defaults=meta['spec'])

        # Upsert curated hardware items
        created_count = 0
        updated_count = 0
        for item in build_catalog_items():
            cat_obj = cat_map[item['category']]
            brand_obj = brand_map[item['brand']]
            slot_img = f'images/categories/{cat_obj.component_slot}.svg'

            prod, created = Product.objects.update_or_create(
                sku=item['sku'],
                defaults={
                    'name': item['name'],
                    'slug': slugify(item['name']),
                    'category': cat_obj,
                    'brand': brand_obj,
                    'price': item['price'],
                    'original_price': item.get('original_price'),
                    'static_image_path': slot_img,
                    'short_description': item['short'],
                    'description': item['desc'],
                    'is_active': True,
                    'is_featured': item.get('featured', False),
                    'is_trending': item.get('trending', False),
                    'is_special_offer': item.get('offer', False),
                    'is_demo_data': True,
                    'spec_verified': True,
                    'spec_source': item['source'],
                },
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

            Inventory.objects.update_or_create(
                product=prod,
                defaults={'quantity': item['stock']},
            )
            HardwareSpecProfile.objects.update_or_create(
                product=prod,
                defaults=item['spec'],
            )

            specs_display = item.get('specs_display', [])
            if specs_display:
                prod.specifications.all().delete()
                for idx, (grp, key, val, unit) in enumerate(specs_display):
                    ProductSpecification.objects.create(
                        product=prod,
                        spec_group=grp,
                        spec_key=key,
                        spec_value=val,
                        unit=unit,
                        is_highlight=(idx < 3),
                        is_verified=True,
                        display_order=idx,
                    )

        self.stdout.write(
            self.style.SUCCESS(
                f'Seed complete: {created_count} created, {updated_count} updated, '
                f'{Product.objects.filter(is_active=True).count()} total active products.'
            )
        )
